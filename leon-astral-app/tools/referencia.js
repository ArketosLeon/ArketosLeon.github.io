    M = n(357.5291092 + 35999.0502909 * T - 0.0001536 * T * T), Mp = n(134.9633964 + 477198.8675055 * T + 0.0087414 * T * T),
    F = n(93.2720950 + 483202.0175233 * T - 0.0036539 * T * T), E = 1 - 0.002516 * T - 0.0000074 * T * T;
  let s = 0;
  for (const [d, m, mp, f, c] of MOON) { const e = Math.abs(m) === 1 ? E : Math.abs(m) === 2 ? E * E : 1; s += c * e * Math.sin((d * D + m * M + mp * Mp + f * F) * R); }
